import { NextRequest, NextResponse } from 'next/server';
import { desc, eq } from 'drizzle-orm';
import { db } from '@/src/db';
import {
  adminActivityLogs,
  projectPhotos,
  reportExportLogs,
} from '@/src/db/schema';
import {
  logAdminSecurityActivity,
  validateAdminRequestSession,
} from '@/src/lib/server-auth';
import { authorizeRoleAccess } from '@/lib/zipblind-auth';
import { getOperationalSnapshot } from '@/src/lib/operational-db';
import { decodePhotoCaptionMetadata } from '@/lib/zipblind-gallery';
import {
  buildOfficialMonthlyReport,
  ensureUniqueMonthlyReportArchive,
  formatIndonesianPeriodMonth,
  getOfficialReportCreationDate,
  type MonthlyReportArchiveEntry,
  type OfficialMonthlyReportData,
} from '@/lib/zipblind-monthly-report';

async function loadAllMonthlyReportsBundle(requestedPeriod?: string) {
  const snapshot = await getOperationalSnapshot();
  const [rawPhotos, rawExportLogs, rawActivityLogs] = await Promise.all([
    db.select().from(projectPhotos).orderBy(desc(projectPhotos.uploadedAt)),
    db.select().from(reportExportLogs).orderBy(desc(reportExportLogs.exportedAt)),
    db
      .select()
      .from(adminActivityLogs)
      .where(eq(adminActivityLogs.actionType, 'AUTO_GENERATE_MONTHLY_REPORT'))
      .orderBy(desc(adminActivityLogs.createdAt)),
  ]);

  const projectMap = new Map(snapshot.projects.map((p) => [p.id, p]));
  const activityMap = new Map(snapshot.activities.map((a) => [a.id, a]));

  const formattedPhotos = rawPhotos.map((ph) => {
    const proj = projectMap.get(ph.projectId);
    const act = ph.activityId ? activityMap.get(ph.activityId) : undefined;
    const decoded = decodePhotoCaptionMetadata(ph.category, ph.caption);

    return {
      id: ph.id,
      projectId: ph.projectId,
      projectCode: proj?.projectCode || 'PRJ-ZB',
      projectTitle: proj?.title || 'Proyek ZIPBLIND',
      activityId: ph.activityId,
      activityType: act?.activityType || decoded.documentationCategory,
      activityDate: act?.startDate || proj?.startDate || '2026-11-10',
      documentationCategory: decoded.documentationCategory,
      caption: decoded.cleanCaption,
      uploadedAt: ph.uploadedAt.toISOString(),
      imageUrl: `/api/admin/gallery/download/${ph.id}`,
    };
  });

  // Kumpulkan periode bulan yang tersedia dari aktivitas nyata + arsip (Oktober, November, Desember 2026)
  const periodSet = new Set<string>(['2026-10', '2026-11', '2026-12']);
  for (const act of snapshot.activities) {
    if (act.startDate && act.startDate.length >= 7) {
      periodSet.add(act.startDate.slice(0, 7));
    }
    if (act.endDate && act.endDate.length >= 7) {
      periodSet.add(act.endDate.slice(0, 7));
    }
  }
  for (const log of rawExportLogs) {
    if (log.reportPeriodMonth && log.reportPeriodMonth.length >= 7) {
      periodSet.add(log.reportPeriodMonth.slice(0, 7));
    }
  }
  for (const log of rawActivityLogs) {
    const meta = (log.metadata || {}) as { periodMonth?: string };
    if (meta.periodMonth && meta.periodMonth.length >= 7) {
      periodSet.add(meta.periodMonth.slice(0, 7));
    }
  }

  const sortedPeriods = Array.from(periodSet).sort((a, b) => b.localeCompare(a));

  const reportsByPeriod: Record<string, OfficialMonthlyReportData> = {};
  let archives: MonthlyReportArchiveEntry[] = [];

  for (const period of sortedPeriods) {
    const report = buildOfficialMonthlyReport({
      periodMonth: period,
      activities: snapshot.activities,
      projects: snapshot.projects,
      technicians: snapshot.technicians,
      products: snapshot.products,
      photos: formattedPhotos,
    });
    reportsByPeriod[period] = report;

    const periodExports = rawExportLogs.filter(
      (e) => e.reportPeriodMonth.slice(0, 7) === period
    );
    const pdfCount = periodExports.filter((e) => e.exportFormat === 'PDF').length;
    const excelCount = periodExports.filter((e) => e.exportFormat === 'EXCEL').length;
    const latestExport = periodExports[0]?.exportedAt
      ? periodExports[0].exportedAt.toISOString()
      : null;

    const candidateEntry: MonthlyReportArchiveEntry = {
      id: `archive-${period}`,
      periodMonth: period,
      periodLabel: report.periodLabel,
      reportTitle: `Laporan Operasional Bulanan — ${report.periodLabel}`,
      reportDocumentNumber: report.reportDocumentNumber,
      officialGeneratedDate: report.officialGeneratedDate,
      officialGeneratedDateLabel: report.officialGeneratedDateLabel,
      isAutoGenerated: true,
      totalProjects: report.totalProjects,
      newProjectsCount: report.newProjectsCount,
      continuingProjectsCount: report.continuingProjectsCount,
      completedProjects: report.completedProjects,
      ongoingProjects: report.ongoingProjects,
      delayedProjects: report.delayedProjects,
      totalActivities: report.totalActivitiesInPeriod,
      totalSets: report.totalSets,
      completedSets: report.completedSets,
      photosCount: report.photoDocumentation.length,
      pdfExportCount: pdfCount,
      excelExportCount: excelCount,
      lastExportedAt: latestExport,
    };

    const dedup = ensureUniqueMonthlyReportArchive(archives, candidateEntry);
    archives = dedup.archives;
  }

  const targetPeriod =
    requestedPeriod && reportsByPeriod[requestedPeriod]
      ? requestedPeriod
      : reportsByPeriod['2026-11']
        ? '2026-11'
        : sortedPeriods[0];

  return {
    selectedPeriod: targetPeriod,
    selectedReport: reportsByPeriod[targetPeriod],
    reportsByPeriod,
    archives,
    exportLogs: rawExportLogs.slice(0, 20).map((e) => ({
      id: e.id,
      reportPeriodMonth: e.reportPeriodMonth,
      reportTitle: e.reportTitle,
      exportFormat: e.exportFormat,
      exportedByRole: e.exportedByRole,
      exportedAt: e.exportedAt.toISOString(),
    })),
    registeredAutoPeriodMonths: new Set(
      rawActivityLogs
        .map((l) => ((l.metadata || {}) as { periodMonth?: string }).periodMonth)
        .filter((x): x is string => Boolean(x))
    ),
  };
}

export async function GET(req: NextRequest) {
  const explicitRole = req.headers.get('x-zipblind-role');
  if (explicitRole === 'technician') {
    const rbac = authorizeRoleAccess({
      role: 'technician',
      httpMethod: 'GET',
      targetScope: 'admin',
    });
    return NextResponse.json(
      { error: rbac.message, code: rbac.code },
      { status: rbac.status }
    );
  }

  const authCheck = await validateAdminRequestSession(req);
  if (!authCheck.authenticated || !authCheck.admin) {
    return NextResponse.json(
      { error: authCheck.message, code: authCheck.code },
      { status: authCheck.status }
    );
  }

  const { searchParams } = new URL(req.url);
  const period = searchParams.get('period') || '2026-11';

  const bundle = await loadAllMonthlyReportsBundle(period);

  return NextResponse.json(
    {
      selectedPeriod: bundle.selectedPeriod,
      selectedReport: bundle.selectedReport,
      reportsByPeriod: bundle.reportsByPeriod,
      archives: bundle.archives,
      exportLogs: bundle.exportLogs,
    },
    { status: 200 }
  );
}

/**
 * POST /api/admin/monthly-reports
 * Menjalankan pembuatan otomatis / sinkronisasi laporan bulanan resmi untuk periode tertentu
 * dengan proteksi anti-duplikasi (tidak pernah menghasilkan laporan ganda untuk periode yang sama).
 */
export async function POST(req: NextRequest) {
  const explicitRole = req.headers.get('x-zipblind-role');
  if (explicitRole === 'executive' || explicitRole === 'technician') {
    const rbac = authorizeRoleAccess({
      role: explicitRole,
      httpMethod: 'POST',
      targetScope: explicitRole === 'executive' ? 'executive' : 'admin',
    });
    return NextResponse.json(
      { error: rbac.message, code: rbac.code },
      { status: rbac.status }
    );
  }

  const authCheck = await validateAdminRequestSession(req);
  if (!authCheck.authenticated || !authCheck.admin) {
    return NextResponse.json(
      { error: authCheck.message, code: authCheck.code },
      { status: authCheck.status }
    );
  }

  try {
    const body = await req.json();
    const rawPeriod = String(body.periodMonth || '2026-11').trim().slice(0, 7);
    if (!/^\d{4}-\d{2}$/.test(rawPeriod)) {
      return NextResponse.json(
        { error: 'Format periode laporan tidak valid. Gunakan format YYYY-MM.' },
        { status: 400 }
      );
    }

    const bundleBefore = await loadAllMonthlyReportsBundle(rawPeriod);
    const existingArchive = bundleBefore.archives.find(
      (a) => a.periodMonth === rawPeriod
    );
    const alreadyLoggedInDb = bundleBefore.registeredAutoPeriodMonths.has(rawPeriod);

    // Apabila periode sudah ada di arsip utama (2026-10, 2026-11, 2026-12) atau sudah pernah dibuat sebelumnya:
    // Pastikan TIDAK menghasilkan laporan ganda untuk periode yang sama!
    if (
      alreadyLoggedInDb ||
      ['2026-10', '2026-11', '2026-12'].includes(rawPeriod)
    ) {
      const dedupCheck = ensureUniqueMonthlyReportArchive(
        bundleBefore.archives,
        existingArchive || {
          id: `archive-${rawPeriod}`,
          periodMonth: rawPeriod,
          periodLabel: formatIndonesianPeriodMonth(rawPeriod),
          reportTitle: `Laporan Operasional Bulanan — ${formatIndonesianPeriodMonth(rawPeriod)}`,
          reportDocumentNumber: `RPT-ZB-${rawPeriod.replace('-', '')}-01`,
          officialGeneratedDate: getOfficialReportCreationDate(rawPeriod).isoDate,
          officialGeneratedDateLabel: getOfficialReportCreationDate(rawPeriod).label,
          isAutoGenerated: true,
          totalProjects: 0,
          newProjectsCount: 0,
          continuingProjectsCount: 0,
          completedProjects: 0,
          ongoingProjects: 0,
          delayedProjects: 0,
          totalActivities: 0,
          totalSets: 0,
          completedSets: 0,
          photosCount: 0,
          pdfExportCount: 0,
          excelExportCount: 0,
          lastExportedAt: null,
        }
      );

      return NextResponse.json(
        {
          duplicatePrevented: true,
          periodMonth: rawPeriod,
          officialGeneratedDate: getOfficialReportCreationDate(rawPeriod).isoDate,
          officialGeneratedDateLabel: getOfficialReportCreationDate(rawPeriod).label,
          message: `Laporan bulanan resmi periode ${formatIndonesianPeriodMonth(
            rawPeriod
          )} (Jadwal Pembuatan Otomatis: ${
            getOfficialReportCreationDate(rawPeriod).label
          }) sudah tersedia di arsip. Sistem mencegah pembuatan laporan ganda untuk periode yang sama.`,
          selectedPeriod: rawPeriod,
          selectedReport: bundleBefore.reportsByPeriod[rawPeriod],
          reportsByPeriod: bundleBefore.reportsByPeriod,
          archives: dedupCheck.archives,
          exportLogs: bundleBefore.exportLogs,
        },
        { status: 200 }
      );
    }

    // Jika periode baru belum pernah terdaftar, catat pembuatan otomatis tanggal 1 bulan berikutnya
    const schedule = getOfficialReportCreationDate(rawPeriod);
    await logAdminSecurityActivity({
      adminId: authCheck.admin.id,
      actionType: 'AUTO_GENERATE_MONTHLY_REPORT',
      entityName: 'report_export_logs',
      description: `Pembuatan otomatis Laporan Bulanan Resmi periode ${formatIndonesianPeriodMonth(
        rawPeriod
      )} (Tanggal Rilis Resmi: ${schedule.label})`,
      metadata: {
        periodMonth: rawPeriod,
        officialGeneratedDate: schedule.isoDate,
      },
    });

    const bundleAfter = await loadAllMonthlyReportsBundle(rawPeriod);
    return NextResponse.json(
      {
        duplicatePrevented: false,
        periodMonth: rawPeriod,
        officialGeneratedDate: schedule.isoDate,
        officialGeneratedDateLabel: schedule.label,
        message: `Laporan bulanan resmi periode ${formatIndonesianPeriodMonth(
          rawPeriod
        )} berhasil dibuat secara otomatis (Tanggal Resmi: ${schedule.label}).`,
        selectedPeriod: rawPeriod,
        selectedReport: bundleAfter.reportsByPeriod[rawPeriod],
        reportsByPeriod: bundleAfter.reportsByPeriod,
        archives: bundleAfter.archives,
        exportLogs: bundleAfter.exportLogs,
      },
      { status: 201 }
    );
  } catch (err) {
    console.error('Error POST /api/admin/monthly-reports:', err);
    return NextResponse.json(
      { error: 'Gagal memproses pembuatan laporan bulanan.' },
      { status: 500 }
    );
  }
}
